"""Write js/media-index.js: the list of every artwork and video file in assets/.

The preview looks media up by naming convention (assets/characters/<id>.webp,
assets/videos/<id>/<jutsu-word>.mp4, ...). With this index the browser only
requests files that really exist, instead of probing every candidate path and
filling the console with 404s.

Run from the repo root after adding, renaming or removing media:
    python tools/build_media_index.py

If js/media-index.js is missing, the site falls back to probing (slower, still works).
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent.parent
FOLDERS = ["assets/characters", "assets/tail-beast", "assets/eyes", "assets/colossi", "assets/kekkei-genkai", "assets/weapons", "assets/videos", "assets/thumbs"]
MEDIA = {".webp", ".png", ".jpg", ".jpeg", ".gif", ".mp4", ".webm"}


def main():
    files = sorted(
        p.relative_to(ROOT).as_posix()
        for folder in FOLDERS
        for p in (ROOT / folder).rglob("*")
        if p.is_file() and p.suffix.lower() in MEDIA
    )
    out = ROOT / "js" / "media-index.js"
    body = ",\n  ".join(json.dumps(f, ensure_ascii=False) for f in files)
    out.write_text(
        "/* GENERATED by tools/build_media_index.py, do not edit by hand.\n"
        "   Every media file under assets/; the preview only requests paths listed here. */\n"
        f"window.MEDIA_INDEX = [\n  {body}\n];\n",
        encoding="utf-8", newline="\n",
    )
    print(f"wrote {out.relative_to(ROOT).as_posix()} ({len(files)} files)")


if __name__ == "__main__":
    main()
